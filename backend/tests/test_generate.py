def test_generate_rejects_plaintext_password(client: TestClient) -> None:
    """Passwords supplied as plain text must be rejected with 422."""
    payload = {
        "agent_target": "claude",
        "high_level_description": "Skill that reads from a Postgres database.",
        "context_materials": [
            {
                "connector_type": "postgres",
                "connection_metadata": {
                    "host": "db.example.com",
                    "port": 5432,
                    "database": "mydb",
                    "username": "admin",
                    "password_env_ref": "plaintext_password_not_allowed",
                },
                "description": (
                    "Postgres DB with order data – agent must understand the schema."
                ),
            }
        ],
    }
    resp = client.post("/api/v1/generate", json=payload)
    assert resp.status_code == 422


