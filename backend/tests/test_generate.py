def test_download_zip(client: TestClient) -> None:
    payload = {
        "agent_target": "claude",
        "high_level_description": "Skill to summarise meeting notes for project managers.",
        "context_materials": [],
    }
    gen_resp = client.post("/api/v1/generate", json=payload)
    token = gen_resp.json()["download_token"]

    dl_resp = client.get(f"/api/v1/download/{token}")
    assert dl_resp.status_code == 200
    assert dl_resp.headers["content-type"] == "application/zip"

    zf = zipfile.ZipFile(io.BytesIO(dl_resp.content))
    names = zf.namelist()
    assert "SKILL.md" in names
    assert "README.md" in names


