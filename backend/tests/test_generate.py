def test_generate_claude(client: TestClient) -> None:
    payload = {
        "agent_target": "claude",
        "high_level_description": (
            "Skill to review Node.js backend pull requests following "
            "Stefanini internal coding standards."
        ),
        "context_materials": [
            {
                "connector_type": "rest_api",
                "connection_metadata": {
                    "host": "https://api.example.com",
                    "api_key_env_ref": "$env:MY_API_KEY",
                },
                "description": (
                    "Company REST API – the agent should understand the available "
                    "endpoints and expected request/response shapes."
                ),
            }
        ],
    }
    resp = client.post("/api/v1/generate", json=payload)
    assert resp.status_code == 200
    data = resp.json()
    assert "artifacts" in data
    assert "suggested_prompt" in data
    assert "download_token" in data

    paths = [a["path"] for a in data["artifacts"]]
    assert "SKILL.md" in paths
    assert "README.md" in paths


