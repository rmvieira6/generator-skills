# ---------------------------------------------------------------------------
# Stub LLM client
# ---------------------------------------------------------------------------


class StubLLMClient:
    """Returns a fixed string; no network calls."""

    async def complete(self, system_prompt: str, user_prompt: str) -> str:
        return "# Stub Skill\n\nThis is a test artifact generated by the stub LLM."


def _stub_llm() -> LLMClient:
    return StubLLMClient()  # type: ignore[return-value]


